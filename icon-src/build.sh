#!/bin/bash
# Build SuperHub's icon PNGs (280 px, 16 greys) and src/icons.ts.
#   bash icon-src/build.sh            (from the plugin folder)
# Sketch icons come from sketch.py; the hand-supplied ones live in icon-src/supplied/.
set -e
cd "$(dirname "$0")/.."
T=$(mktemp -d)
python3 -I icon-src/sketch.py "$T" >/dev/null
mkdir -p assets/hub/icons
png() { magick "$1" -colorspace Gray -fuzz 6% -trim +repage -resize 264x264 -background white -gravity center -extent 280x280 -dither None -colors 16 -define png:color-type=0 "$2"; }
for f in "$T"/*.svg; do
  n=$(basename "$f" .svg)
  case $n in frame|pframe) continue;; esac
  rsvg-convert -w 600 -b white "$f" -o "$T/$n.png" && png "$T/$n.png" "assets/hub/icons/$n.png" &
done
for f in icon-src/supplied/*.png; do png "$f" "assets/hub/icons/$(basename "$f")" & done
for f in icon-src/supplied/*.svg; do n=$(basename "$f" .svg); (rsvg-convert -w 1024 -b white "$f" -o "$T/$n.png" && png "$T/$n.png" "assets/hub/icons/$n.png") & done
# the clock frame, at its on-screen size (860 x 300 dp at 2 px/dp)
(rsvg-convert -w 1720 "$T/frame.svg" -o "$T/frame.png" && magick "$T/frame.png" -colorspace Gray -dither None -colors 16 assets/hub/frame.png) &
(rsvg-convert -w 400 "$T/pframe.svg" -o "$T/pframe.png" && magick "$T/pframe.png" -colorspace Gray -dither None -colors 16 assets/hub/pframe.png) &
wait
rm -rf "$T"
{
  echo '// Generated by icon-src/build.sh: every picture icon a home button can use.'
  echo 'export const ICONS: Record<string, any> = {'
  for f in assets/hub/icons/*.png; do n=$(basename "$f" .png); echo "  '$n': require('../assets/hub/icons/$n.png'),"; done
  echo '};'
} > src/icons.ts
ls assets/hub/icons | wc -l
